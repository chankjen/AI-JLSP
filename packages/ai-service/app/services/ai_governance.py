# 3. EXPLAINABILITY LAYER — SHAP/LIME PROXY (PRD Sec 7 - Explainability)
# Provides feature attribution for model transparency per Constitution Art 47
# ============================================================================

@dataclass
class ExplainabilityReport:
    """SHAP/LIME-style explanation for an AI decision."""
    model_name: str
    prediction: Any
    confidence: float
    top_features: List[Dict[str, Any]]      # Feature name → contribution weight
    decision_boundary: str                   # Human-readable boundary explanation
    adverse_factors: List[str]               # Factors that reduced confidence
    supporting_factors: List[str]            # Factors that increased confidence
    constitutional_basis: str                # Applicable constitutional/statutory provision
    generated_at: str = field(default_factory=lambda: datetime.utcnow().isoformat())

    def to_dict(self) -> Dict[str, Any]:
        return {
            "model_name": self.model_name,
            "prediction": self.prediction,
            "confidence": self.confidence,
            "top_features": self.top_features,
            "decision_boundary": self.decision_boundary,
            "adverse_factors": self.adverse_factors,
            "supporting_factors": self.supporting_factors,
            "constitutional_basis": self.constitutional_basis,
            "generated_at": self.generated_at,
        }


def explain_document_validation(
    text: str,
    issues: List[Dict],
    confidence: float,
    doc_type: str,
) -> ExplainabilityReport:
    """
    Produce a SHAP/LIME-style explanation for a document validation result.
    In production, replace keyword attribution with real SHAP values.
    """
    features = []
    adverse = []
    supporting = []

    # Structural attribution (keyword-based proxy for SHAP feature importance)
    checks = {
        "execution_clause": ("signed|executed|witness", 0.3),
        "jurisdiction_marker": ("court|magistrate|high court", 0.25),
        "party_identification": ("plaintiff|defendant|claimant|respondent", 0.2),
        "case_reference": (r"\d{3,}/\d{4}", 0.15),
        "date_present": (r"\d{1,2}[/-]\d{1,2}[/-]\d{2,4}", 0.1),
    }

    import re
    for feature_name, (pattern, weight) in checks.items():
        found = bool(re.search(pattern, text, re.IGNORECASE))
        direction = "positive" if found else "negative"
        features.append({
            "feature": feature_name,
            "found": found,
            "weight": round(weight * (1 if found else -1), 3),
            "direction": direction,
        })
        if found:
            supporting.append(f"{feature_name.replace('_', ' ').title()} detected.")
        else:
            adverse.append(f"{feature_name.replace('_', ' ').title()} not found — required for {doc_type}.")

    return ExplainabilityReport(
        model_name="legal-bert-ke-v1",
        prediction="valid" if not issues else "invalid",
        confidence=confidence,
        top_features=sorted(features, key=lambda f: abs(f["weight"]), reverse=True),
        decision_boundary=(
            f"Document classified as {'valid' if not issues else 'invalid'} based on "
            f"{len(supporting)} supporting and {len(adverse)} adverse structural markers."
        ),
        adverse_factors=adverse,
        supporting_factors=supporting,
        constitutional_basis=(
            "Civil Procedure Rules (CPR) 2010 Order 6; Constitution of Kenya Art 50 (fair hearing); "
            "AI-JLSP PRD Sec 7 Explainability Requirement."
        ),
    )


