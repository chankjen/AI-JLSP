# 4. BIAS MITIGATION AUDIT LOGGER (PRD Sec 7 - Bias Mitigation)
# Logs demographic signals for quarterly fairness audits per ODPC alignment
# ============================================================================

class BiasAuditLogger:
    """
    Records AI prediction metadata for quarterly fairness audits.
    ODPC-aligned documentation requirement per PRD Sec 7.
    Data is pseudonymised per DPA Sec 2.
    """

    @staticmethod
    def _pseudonymise(user_id: Optional[str]) -> Optional[str]:
        """SHA-256 pseudonymisation — DPA Sec 2 compliant."""
        if not user_id:
            return None
        return "uid_" + hashlib.sha256(user_id.encode()).hexdigest()[:16]

    @classmethod
    def log(
        cls,
        action_type: str,
        model_name: str,
        confidence: float,
        outcome: str,
        user_id: Optional[str] = None,
        case_type: Optional[str] = None,
        jurisdiction: Optional[str] = None,
    ) -> Dict[str, Any]:
        """Produce a bias audit record for storage and quarterly review."""
        record = {
            "audit_event": "ai_prediction",
            "timestamp": datetime.utcnow().isoformat(),
            "action_type": action_type,
            "model_name": model_name,
            "confidence": round(confidence, 4),
            "outcome": outcome,
            "pseudonymised_user_id": cls._pseudonymise(user_id),
            "case_type": case_type,
            "jurisdiction": jurisdiction or "KE",  # Data sovereignty — Kenya default
            "fairness_flags": [],
            "requires_quarterly_review": True,
        }

        # Flag low-confidence predictions for bias investigation
        if confidence < 0.65:
            record["fairness_flags"].append("LOW_CONFIDENCE_PREDICTION")
            logger.warning(
                "Bias audit flag: LOW_CONFIDENCE_PREDICTION [action=%s, confidence=%.2f]",
                action_type, confidence,
            )

        logger.info("BiasAudit: %s", record)
        return record


