AI_ADVISORY_DISCLAIMER = (
    "⚠️ NON-BINDING ADVISORY — This output is generated by an AI assistive tool. "
    "It does not constitute legal advice, judicial determination, or official guidance. "
    "All decisions require human review and approval. "
    "[AI-JLSP § Governance Policy v1.0 | DPA Cap 411C Sec 31]"
)


def attach_disclaimer(result: Dict[str, Any]) -> Dict[str, Any]:
    """Attach the non-binding advisory disclaimer to all AI outputs."""
    result["ai_disclaimer"] = AI_ADVISORY_DISCLAIMER
    result["requires_human_review"] = True
    result["governance_version"] = "1.0"
    return result


