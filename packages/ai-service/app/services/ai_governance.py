# 2. HUMAN-IN-THE-LOOP GATE (PRD Sec 7 - Human-in-the-Loop)
# Final legal/judicial decisions require advocate/judge approval; AI assists only
# ============================================================================

class HumanInTheLoopGate:
    """
    Enforces human review requirements for all critical AI decisions.
    Constitution Art 160 (judicial independence) + PRD Sec 7.
    """

    # Confidence threshold below which human review is mandatory
    MANDATORY_REVIEW_THRESHOLD = 0.75

    # Actions that always require human approval regardless of confidence
    ALWAYS_REQUIRES_HUMAN = {
        "case_outcome_prediction",
        "tdr_objection_decision",
        "document_rejection",
        "adr_pathway_decision",
    }

    @classmethod
    def evaluate(
        cls,
        action_type: str,
        confidence: float,
        result: Dict[str, Any],
    ) -> Dict[str, Any]:
        """
        Evaluate whether a human must approve this AI output.
        Returns enriched result with human-in-the-loop metadata.
        """
        requires_approval = (
            action_type in cls.ALWAYS_REQUIRES_HUMAN
            or confidence < cls.MANDATORY_REVIEW_THRESHOLD
        )

        result["human_review"] = {
            "required": requires_approval,
            "reason": (
                "Action type mandates human approval per PRD Sec 7."
                if action_type in cls.ALWAYS_REQUIRES_HUMAN
                else (
                    f"Confidence {confidence:.0%} below {cls.MANDATORY_REVIEW_THRESHOLD:.0%} threshold."
                    if requires_approval
                    else "Confidence sufficient; human review recommended but not mandatory."
                )
            ),
            "reviewed_by": None,  # Populated when a human approves
            "reviewed_at": None,
        }
        return result


